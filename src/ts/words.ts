export function titleFor(points: number): { name: string; next: { name: string; remain: number } | null } {
  let idx = 0;
  TITLES.forEach((t, i) => {
    if (points >= t.min) idx = i;
  });
  const nextT = TITLES[idx + 1];
  return {
    name: TITLES[idx].name,
    next: nextT ? { name: nextT.name, remain: nextT.min - points } : null,
  };
}
